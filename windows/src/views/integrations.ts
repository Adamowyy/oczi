// ── Cal.com ───────────────────────────────────────────────────────────────────

function calcomCard(): HTMLElement {
  const bookings = arr("integration_calcom", "bookings")
    .slice()
    .sort((a, b) => new Date(String(a.start)).getTime() - new Date(String(b.start)).getTime());
  const rows = h("div", { class: "int-rows tight" });
  if (bookings.length === 0) {
    rows.append(h("div", { class: "int-empty", text: t("int.noMeetings") }));
  }
  for (const b of bookings.slice(0, 3)) {
    const when = new Date(String(b.start));
    const day = when.toLocaleDateString(undefined, { day: "2-digit", month: "2-digit" });
    const time = when.toLocaleTimeString(undefined, { hour: "2-digit", minute: "2-digit" });
    rows.append(
      h(
        "div",
        { class: "int-row" },
        dot("#C9956A", 4),
        h("span", { class: "int-time", text: `${day} ${time}` }),
        h("span", { class: "int-name", text: String(b.title ?? "Spotkanie") }),
      ),
    );
  }
  return h("div", { class: "int-card" }, header("#C9956A", "Cal.com", "Harmonogram"), rows);
}

// ── n8n ───────────────────────────────────────────────────────────────────────

function n8nCard(task: AgentTask, onDetail: () => void, openSettings: () => void): HTMLElement {
  const hasActivity = task.steps.length > 0 && (task.state === "finished" || task.state === "error");
  if (!hasActivity) return idleCard(task, openSettings);
  const success = task.state === "finished";
  const accent = success ? "#22C55E" : "#F4505E";
  return h(
    "div",
    { class: "int-card" },
    header("#F29B38", "n8n", t("int.workflow")),
    h(
      "div",
      { class: "int-actions" },
      h(
        "button",
        {
          class: "int-pill",
          style: `background:${accent}1a;border-color:${accent}38`,
          onclick: onDetail,
        },
        dot(accent, 5),
        h("span", { class: "int-name", text: task.steps[0] ?? t("int.workflow") }),
        svg(ICONS.ellipsis, 8),
      ),
    ),
  );
}

function n8nDetail(task: AgentTask, onBack: () => void): HTMLElement {
  const success = task.state === "finished";
  const accent = success ? "#22C55E" : "#F4505E";
  const detail = task.steps[1];
  return h(
    "div",
    { class: "int-card detail" },
    h(
      "div",
      { class: "int-detail-head" },
      h("button", { class: "int-back", onclick: onBack }, svg(ICONS.chevronLeft, 10, { stroke: 2.4 })),
      dot(accent, 6),
      h("b", { text: task.steps[0] ?? t("int.workflow") }),
      h("span", {
        class: "int-badge",
        style: `color:${accent};background:${accent}24`,
        text: success ? "Sukces" : "Niepowodzenie",
      }),
    ),
    detail
      ? h("pre", { class: "int-detail-text", text: detail })
      : h("div", {
          class: "int-status",
          text: success ? t("int.finishedOk") : t("int.noDetails"),
        }),
  );
}

// ── This PC ───────────────────────────────────────────────────────────────────

/** A 0–100 number read as a colour: quiet with room to spare, red when there is none. */
function loadColor(percent: number): string {
  if (percent >= 85) return "#F4505E";
  if (percent >= 60) return "#F5A524";
  return "#22C55E";
}

const gb = (bytes: unknown) => `${(Number(bytes ?? 0) / 1024 ** 3).toFixed(1)} GB`;

function procList(procs: Record<string, unknown>[]): HTMLElement {
  const list = h("div", { class: "int-procs" }, h("span", { class: "int-procs-title", text: t("int.pcTop") }));
  procs.forEach((p, i) => {
    const name = String(p.name ?? "");
    list.append(
      h(
        "div",
        { class: "int-proc" },
        h("i", { text: `${i + 1}.` }),
        h("b", { text: name.length > 17 ? `${name.slice(0, 16)}…` : name }),
        h("span", { text: gb(p.bytes) }),
      ),
    );
  });
  return list;
}

/** One reading: what it is, how full, and the number itself. The bar carries the
 *  percentage so the value can carry the absolute figure. */
function gaugeRow(icon: string, label: string, percent: number, value: string): HTMLElement {
  const color = loadColor(percent);
  const fill = h("i", { class: "int-gauge-fill" });
  fill.style.width = `${Math.max(2, Math.min(100, percent)).toFixed(0)}%`;
  fill.style.background = color;
  return h(
    "div",
    { class: "int-gauge" },
    h("i", { class: "int-stat-icon", style: `color:${color}` }, svg(icon, 11, { stroke: 1.7 })),
    h("span", { class: "int-stat-label", text: label }),
    h("span", { class: "int-gauge-track" }, fill),
    h("span", { class: "int-stat-value", text: value }),
  );
}

function pcCard(): HTMLElement {
  const d = get("integration_pc");
  const cpu = Number(d.cpu ?? 0);
  const memPercent = Number(d.memPercent ?? 0);
  const disks = Array.isArray(d.disks) ? (d.disks as Record<string, unknown>[]) : [];
  const disk = disks[0];
  const battery = d.battery == null ? null : Number(d.battery);

  const kind =
    battery == null
      ? ""
      : `${t("int.battery")} ${battery}%${d.plugged === true ? " · ⚡" : ""}`;

  const rows = h("div", { class: "int-stats" });
  rows.append(gaugeRow(ICONS.cpu, t("int.cpu"), cpu, d.cpu == null ? "…" : `${Math.round(cpu)}%`));
  rows.append(
    gaugeRow(
      ICONS.memory,
      t("int.memory"),
      memPercent,
      Number(d.memTotalBytes ?? 0) > 0 ? `${gb(d.memUsedBytes)} / ${gb(d.memTotalBytes)}` : "—",
    ),
  );
  if (disk) {
    rows.append(
      gaugeRow(
        ICONS.disk,
        String(disk.mount ?? "C:"),
        Number(disk.usedPercent ?? 0),
        t("int.diskFree", gb(disk.freeBytes)),
      ),
    );
  }
  const procs = Array.isArray(d.procs) ? (d.procs as Record<string, unknown>[]) : [];
  if (procs.length > 0) rows.append(procList(procs));
  return h("div", { class: "int-card" }, header("#4CC2FF", "PC", kind), rows);
}

// ── Dispatch ──────────────────────────────────────────────────────────────────

export interface IntegrationCardHooks {
  detailOpen: boolean;
  openDetail(): void;
  closeDetail(): void;
  openSettings(): void;
}

/** True when this integration has data worth showing instead of the idle card. */
export function hasIntegrationData(id: string): boolean {
  const info = State.integrations[id];
  if (!info || info.error) return false;
  switch (id) {
    case "integration_vercel":
      return arr(id, "deployments").length > 0;
    case "integration_resend":
      return arr(id, "emails").length > 0;
    case "integration_github":
      return get(id).totalRepos != null;
    case "integration_stripe":
      return info.loaded;
    case "integration_notion":
      return arr(id, "pages").length > 0;
    case "integration_calcom":
      return info.loaded;
    case "integration_pc":
      // Always loaded once the first sample lands, there is nothing to configure.
      return info.loaded;
    case "integration_music":
      // Anything the OS reports is worth a card, including "nothing playing".
      return info.loaded;
    default:
      return false;
  }
}

export function renderIntegrationCard(task: AgentTask, hooks: IntegrationCardHooks): HTMLElement {
  if (task.id === "integration_n8n") {
    const hasActivity = task.steps.length > 0 && (task.state === "finished" || task.state === "error");
    return hooks.detailOpen && hasActivity
      ? n8nDetail(task, hooks.closeDetail)
      : n8nCard(task, hooks.openDetail, hooks.openSettings);
  }
  if (task.id === "integration_vercel" && hasIntegrationData(task.id)) {
    return hooks.detailOpen ? vercelDetail(hooks.closeDetail) : vercelCard(hooks.openDetail);
  }
  if (!hasIntegrationData(task.id)) return idleCard(task, hooks.openSettings);

  switch (task.id) {
    case "integration_resend":
      return resendCard();
    case "integration_github":
      return githubCard();
    case "integration_stripe":
      return stripeCard();
    case "integration_notion":
      return notionCard();
    case "integration_calcom":
      return calcomCard();
    case "integration_pc":
      return pcCard();
    case "integration_music": {
      // Inside the overview the card keeps the integration padding, which leaves
      // room for Iskra on the left; on the home screen it takes the pills' slot.
      return h("div", { class: "int-card" }, buildMusicCard());
    }
    default:
      return idleCard(task, hooks.openSettings);
  }
}

